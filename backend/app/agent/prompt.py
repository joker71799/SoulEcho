# 近期会话历史不拼在这里，而是以 HumanMessage / AIMessage 多轮原样传入，更 LLM-native。
# 末尾的【记忆铁律】是关键兜底：疗愈人设本身有“我记得你…”的倾向，不给硬约束就容易编造。
